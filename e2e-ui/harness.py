"""Shared harness for the real-input UI e2e suite.

Targets the deployed site (default https://video.synload.com; override with
E2E_UI_BASE). The suite REUSES a fixed set of test accounts (one per role,
registered once, then logged in on every run — there is no user-delete API,
so registering a fresh account per run would pile them up on the live site).
Videos are created with REAL ffmpeg-generated bytes, so the worker genuinely
transcodes them to `ready` — the full pipeline, no SQL flips.

"Real input" means the browser's own input pipeline: Playwright key events for
typing, real mouse events for clicks, a genuine file input for uploads, and
CDP Input.dispatch* for touch swipes and mouse wheel (see ui.py).

The suite is self-contained and self-cleaning: Ctx.cleanup() deletes every
video and playlist this run created (which cascade-deletes the notifications
they generated). On startup, each account's notifications are marked read so
leftovers from a crashed run can't skew exact-count checks.
"""
import json
import os
import subprocess
import time
import urllib.error
import urllib.request

BASE = os.environ.get("E2E_UI_BASE", "https://video.synload.com")
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)
FFMPEG = os.environ.get("E2E_FFMPEG", "ffmpeg")
VIDEOS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "videos")


class Client:
    """Minimal API client (same conventions as e2e/harness.py)."""

    def __init__(self, base=BASE):
        self.base = base.rstrip("/")

    def request(self, method, path, token=None, body=None, raw=None,
                ctype="application/json", timeout=60):
        url = self.base + path
        if raw is not None:
            data = raw
        elif body is not None:
            data = json.dumps(body).encode()
        else:
            data = None
        r = urllib.request.Request(url, data=data, method=method)
        r.add_header("User-Agent", UA)
        if data is not None:
            r.add_header("Content-Type", ctype)
        if token:
            r.add_header("Authorization", f"Bearer {token}")
        try:
            with urllib.request.urlopen(r, timeout=timeout) as resp:
                txt = resp.read().decode()
                return resp.status, (json.loads(txt) if txt else None)
        except urllib.error.HTTPError as e:
            txt = e.read().decode()
            try:
                return e.code, json.loads(txt)
            except Exception:
                return e.code, txt
        except Exception as e:  # network error
            return 0, f"network error: {e}"

    def get(self, path, token=None, **kw):
        return self.request("GET", path, token, **kw)

    def post(self, path, token=None, body=None, **kw):
        return self.request("POST", path, token, body=body, **kw)

    def patch(self, path, token=None, body=None, **kw):
        return self.request("PATCH", path, token, body=body, **kw)

    def delete(self, path, token=None, **kw):
        return self.request("DELETE", path, token, **kw)


class Results:
    def __init__(self):
        self.passed = 0
        self.failed = 0
        self.skipped = 0
        self.failures = []

    def check(self, name, cond, detail=""):
        if cond:
            self.passed += 1
            print(f"  PASS  {name}")
            return True
        self.failed += 1
        self.failures.append((name, detail))
        print(f"  FAIL  {name}  {detail}")
        return False

    def skip(self, name, reason=""):
        self.skipped += 1
        print(f"  SKIP  {name}  {reason}")


def make_video(path, label, vertical=False, seconds=3, color="blue"):
    """Generate a real H.264 mp4 with a solid color, a burned-in label and a
    running timecode, so the worker has genuine content to transcode."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if vertical:
        size = "720x1280"
    else:
        size = "640x360"
    cmd = [
        FFMPEG, "-y", "-loglevel", "error",
        "-f", "lavfi", "-i", f"color=c={color}:s={size}:r=24:d={seconds}",
        "-f", "lavfi", "-i", "anullsrc=r=44100:cl=stereo",
        "-t", str(seconds),
        "-vf", (
            f"drawtext=text='{label}':fontcolor=white:fontsize=48:"
            f"x=(w-text_w)/2:y=(h-text_h)/2-40,"
            f"drawtext=text='%{{pts\\:hms}}':fontcolor=yellow:fontsize=36:"
            f"x=(w-text_w)/2:y=(h-text_h)/2+40"
        ),
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "23",
        "-c:a", "aac", "-shortest",
        path,
    ]
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    if p.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {p.stderr[-500:]}")
    return path


class Ctx:
    """Test context: users, real videos, ready-waits, cleanup. Shared across modules."""

    def __init__(self):
        self.client = Client()
        self.results = Results()
        self.run_id = int(time.time())
        self.users = {}
        self.videos = {}      # key -> video id
        self.playlists = {}   # key -> playlist id
        self._video_paths = {}  # key -> local path (for reference)

    # ---- users (fixed accounts, reused across runs) ----
    def ensure_user(self, role, name=None):
        """Get a session for the fixed {role} account: log in, register ONCE
        if it doesn't exist yet. Then mark all its notifications read, so a
        crashed previous run can't leave unread leftovers behind. Never
        registers more than once per account."""
        name = name or f"E2E-UI {role.capitalize()}"
        email = f"e2e-ui-{role}@synload.local"
        password = "TestPass123!"
        s, me = self.client.post("/api/auth/login", body={
            "email": email, "password": password})
        if s != 200 or not isinstance(me, dict) or "token" not in me:
            s, me = self.client.post("/api/auth/register", body={
                "name": name, "email": email, "password": password, "channelName": name})
        self.results.check(f"ensure user {role}",
                           s == 200 and isinstance(me, dict) and "token" in me,
                           f"got {s}: {me}")
        if s != 200 or not isinstance(me, dict) or "token" not in me:
            self.users[role] = None
            return None
        s2, me2 = self.client.get("/api/me", token=me["token"])
        me2 = me2 if isinstance(me2, dict) else {}
        # Normalize: clear notifications left by a crashed previous run so
        # exact-count checks (e.g. the unread badge) are deterministic.
        self.client.post("/api/notifications/read-all", token=me["token"])
        self.users[role] = {
            "token": me["token"],
            "user_id": me2.get("id"),
            "channel_id": me2.get("channelId"),
            "email": email,
            "password": password,
            "name": me2.get("name") or name,
        }
        return self.users[role]

    def user(self, role):
        if role not in self.users:
            self.ensure_user(role)
        return self.users[role]

    # ---- videos ----
    def gen_video(self, key, label, vertical=False, seconds=3, color="blue",
                  filename=None):
        """Generate (and cache) a local mp4 for this run."""
        if key not in self._video_paths:
            base = filename or f"{self.run_id}_{key}.mp4"
            path = os.path.join(VIDEOS_DIR, base)
            make_video(path, label, vertical=vertical, seconds=seconds, color=color)
            self._video_paths[key] = path
        return self._video_paths[key]

    def upload_video(self, key, role="owner", title=None, description=None,
                     tags=None, vertical=False, color="blue", is_short=False):
        """Upload a real video via the API (presign + PUT + create). Returns id."""
        u = self.user(role)
        if not u:
            return None
        title = title or f"E2E-UI {key} {self.run_id}"
        path = self.gen_video(key, title, vertical=vertical, color=color)
        size = os.path.getsize(path)
        s, ps = self.client.post("/api/uploads/presign", token=u["token"], body={
            "file_name": os.path.basename(path), "content_type": "video/mp4", "size": size})
        if s != 200 or not isinstance(ps, dict):
            self.results.check(f"presign {key}", False, f"got {s}: {ps}")
            return None
        # PUT the real bytes to the presigned URL.
        with open(path, "rb") as f:
            data = f.read()
        r = urllib.request.Request(ps["upload_url"], data=data, method="PUT")
        r.add_header("User-Agent", UA)
        r.add_header("Content-Type", "video/mp4")
        try:
            with urllib.request.urlopen(r, timeout=120) as resp:
                put_status = resp.status
        except urllib.error.HTTPError as e:
            put_status = e.code
        except Exception as e:
            self.results.check(f"PUT {key}", False, f"network error: {e}")
            return None
        if put_status not in (200, 201):
            self.results.check(f"PUT {key}", False, f"got {put_status}")
            return None
        body = {
            "title": title,
            "description": description or f"e2e-ui {key}",
            "tags": tags or ["e2e-ui", key],
            "object_key": ps["object_key"],
            "visibility": "public",
        }
        if is_short:
            body["isShort"] = True
        s, v = self.client.post("/api/videos", token=u["token"], body=body)
        ok = s in (200, 201) and isinstance(v, dict) and "video" in v
        self.results.check(f"create video {key}", ok, f"got {s}: {v}")
        if ok:
            self.videos[key] = v["video"]["id"]
            return self.videos[key]
        return None

    def wait_ready(self, video_id, timeout=240, poll=5):
        """Poll until the worker marks the video ready. Returns final status."""
        t0 = time.time()
        last = None
        while time.time() - t0 < timeout:
            s, v = self.client.get(f"/api/videos/{video_id}")
            if s == 200 and isinstance(v, dict):
                vid = v.get("video")
                last = vid.get("status") if isinstance(vid, dict) else None
                if last in ("ready", "failed"):
                    return last
            time.sleep(poll)
        return last or "timeout"

    def ensure_ready(self, key, role="owner", title=None, **kw):
        """Create (or reuse) a video and wait for it to be ready. Returns id or None."""
        vid = self.upload_video(key, role=role, title=title, **kw)
        if not vid:
            return None
        status = self.wait_ready(vid)
        self.results.check(f"{key} reaches ready", status == "ready",
                           f"status={status} (worker may still be catching up)")
        return vid if status == "ready" else None

    # ---- playlists ----
    def create_playlist(self, key, role="owner", title=None, public=False,
                        description=None):
        if key in self.playlists:
            return self.playlists[key]
        u = self.user(role)
        if not u:
            return None
        title = title or f"E2E-UI {key} {self.run_id}"
        body = {"title": title, "isPublic": public}
        if description:
            body["description"] = description
        s, p = self.client.post("/api/playlists", token=u["token"], body=body)
        ok = s in (200, 201) and isinstance(p, dict) and "playlist" in p
        self.results.check(f"create playlist {key}", ok, f"got {s}: {p}")
        if ok:
            self.playlists[key] = p["playlist"]["id"]
            return self.playlists[key]
        return None

    # ---- misc ----
    def check(self, name, cond, detail=""):
        return self.results.check(name, cond, detail)

    def skip(self, name, reason=""):
        return self.results.skip(name, reason)

    def cleanup(self):
        """Best-effort: delete every video and playlist this run created."""
        print("--- cleanup ---")
        u = self.users.get("owner")
        if not u:
            return
        for key, vid in list(self.videos.items()):
            s, _ = self.client.delete(f"/api/videos/{vid}", token=u["token"])
            print(f"  delete video {key} ({vid[:8]}): {s}")
        for key, pid in list(self.playlists.items()):
            s, _ = self.client.delete(f"/api/playlists/{pid}", token=u["token"])
            print(f"  delete playlist {key} ({pid[:8]}): {s}")
        # remove generated videos
        for path in list(self._video_paths.values()):
            try:
                os.remove(path)
            except OSError:
                pass
